#!/usr/bin/env python3
"""Refresh OpenAlex citation counts into data/citations.yml.

Usage:
    python3 tools/update_citations.py
    python3 tools/update_citations.py --author A5051152014

The build reads data/citations.yml as an override, so this file can be
regenerated without touching the hand-formatted publications file.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import urllib.parse
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "citations.yml"
DEFAULT_AUTHOR = "A5051152014"  # Sergio Ruocco, OpenAlex


def normalize_doi(value: str | None) -> str:
    if not value:
        return ""
    value = value.strip().lower()
    value = re.sub(r"^https?://(dx\.)?doi\.org/", "", value)
    return value


def normalize_title(value: str | None) -> str:
    if not value:
        return ""
    value = value.lower()
    value = re.sub(r"[^a-z0-9]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def fetch(author: str) -> dict:
    params = {
        "filter": f"author.id:{author}",
        "per-page": "200",
        "select": "doi,title,publication_year,cited_by_count",
    }
    url = "https://api.openalex.org/works?" + urllib.parse.urlencode(params)
    request = urllib.request.Request(url, headers={"User-Agent": "cv-build/1.0"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--author", default=DEFAULT_AUTHOR)
    args = parser.parse_args()

    payload = fetch(args.author)
    by_doi: dict[str, int] = {}
    by_title: dict[str, int] = {}
    for work in payload.get("results", []):
        count = int(work.get("cited_by_count") or 0)
        doi = normalize_doi(work.get("doi"))
        title = normalize_title(work.get("title"))
        if doi:
            by_doi[doi] = count
        if title:
            by_title[title] = count

    # Google Scholar counts are typed by hand into publications.yml; keep the
    # date they were taken so the CV can label them.
    previous = yaml.safe_load(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
    document = {
        "source": "OpenAlex",
        "author_id": args.author,
        "retrieved": dt.date.today().isoformat(),
        "scholar_retrieved": (previous or {}).get("scholar_retrieved", ""),
        "by_doi": dict(sorted(by_doi.items())),
        "by_title": dict(sorted(by_title.items())),
    }
    OUT.write_text(
        "# Generated by tools/update_citations.py — safe to regenerate.\n"
        + yaml.safe_dump(document, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(by_doi)} DOIs, {len(by_title)} titles)")


if __name__ == "__main__":
    main()
